import test from 'node:test';
import assert from 'node:assert/strict';
import { Box3, BoxGeometry, Group, Mesh, MeshBasicMaterial, Vector3 } from 'three';
import { batchMeshes } from '../src/geometry.js';

test('batching preserves world geometry under transformed parents and animated exclusions', () => {
  const scene = new Group();
  const root = new Group();
  root.position.set(5, -3, 2);
  root.rotation.set(.2, .7, -.3);
  scene.add(root);
  const material = new MeshBasicMaterial();
  const nested = new Group();
  nested.position.set(-4, 2, 1);
  nested.rotation.z = .6;
  root.add(nested);
  const a = new Mesh(new BoxGeometry(2, 3, 4), material);
  a.position.set(1, 2, 3);
  nested.add(a);
  const b = new Mesh(new BoxGeometry(1, 2, 3), material);
  b.position.set(-2, 0, 4);
  root.add(b);
  const animated = new Group();
  animated.position.set(12, 0, 0);
  const child = new Mesh(new BoxGeometry(), material);
  animated.add(child);
  root.add(animated);
  scene.updateMatrixWorld(true);
  const worldBounds = new Box3().setFromObject(root, true);
  const result = batchMeshes(root, { exclude: [animated], system: 'habitat' });
  scene.updateMatrixWorld(true);
  const after = new Box3().setFromObject(root, true);
  assert.ok(worldBounds.min.distanceTo(after.min) < 1e-5);
  assert.ok(worldBounds.max.distanceTo(after.max) < 1e-5);
  assert.deepEqual(result, { before: 2, after: 1 });
  assert.equal(child.parent, animated);
  assert.equal(animated.parent, root);
  const merged = root.children.find(x => x.isMesh);
  assert.equal(merged.geometry.index.count, 72);
  assert.equal(merged.userData.system, 'habitat');
  const oldPosition = child.getWorldPosition(new Vector3());
  animated.position.x += 3;
  assert.ok(child.getWorldPosition(new Vector3()).distanceTo(oldPosition) > 2.99);
});
